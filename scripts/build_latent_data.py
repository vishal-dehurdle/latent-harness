#!/usr/bin/env python3
"""Turn think-condition traces on a training split into latent-model training data.

Keeps one correct, finished trace per problem, then stores the frozen
backbone's pooled hidden states over each trace's reasoning (the Sinkhorn
targets) and the reasoning's keyword token ids (the frozen-head targets).
Interrupted runs resume where they stopped.

Example:
  # 1. Traces: the model's own reasoning on GSM8K train
  python scripts/eval_baseline.py --model deepseek-ai/DeepSeek-R1-Distill-Qwen-1.5B \\
      --benchmarks gsm8k_train --conditions think --max-tokens 4096 --batch-size 16 \\
      --out-dir outputs/traces/DeepSeek-R1-Distill-Qwen-1.5B

  # 2. Teacher states
  python scripts/build_latent_data.py \\
      --traces outputs/traces/DeepSeek-R1-Distill-Qwen-1.5B/gsm8k_train__think.jsonl \\
      --out-dir outputs/latent_data/gsm8k_train
"""

import argparse
import glob
import json
import os
import sys

from latent_harness import provenance
from latent_harness.evals import load_problems
from latent_harness.latent import (
    build_meta,
    keyword_token_ids,
    resolve_device,
    select_traces,
    teacher_state_fn,
    write_teacher_store,
)
from latent_harness.latent.data import load_trace_records
from latent_harness.latent.model import default_dtype


def _trace_model_shas(trace_paths):
    shas = set()
    for trace in trace_paths:
        for path in glob.glob(os.path.join(os.path.dirname(os.path.abspath(trace)), "manifest-*.json")):
            with open(path, encoding="utf-8") as f:
                shas.add(json.load(f).get("model_sha"))
    return shas


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--traces", nargs="+", required=True, help="think-condition JSONL files from eval_baseline.py")
    parser.add_argument("--model", default="deepseek-ai/DeepSeek-R1-Distill-Qwen-1.5B")
    parser.add_argument("--revision", default="main")
    parser.add_argument("--out-dir", required=True)
    parser.add_argument("--max-reasoning-tokens", type=int, default=4096, help="Drop traces that reasoned longer")
    parser.add_argument("--max-states", type=int, default=128, help="Teacher states kept per trace after pooling")
    parser.add_argument("--batch-size", type=int, default=4, help="Traces per teacher forward pass")
    parser.add_argument("--limit", type=int, help="Only the first N selected traces (smoke tests)")
    parser.add_argument("--device", default="auto")
    args = parser.parse_args()

    from transformers import AutoModelForCausalLM, AutoTokenizer

    sha = provenance.model_sha(args.model, args.revision)
    trace_shas = _trace_model_shas(args.traces)
    if trace_shas != {sha}:
        sys.exit(f"Traces were generated by model revision(s) {sorted(map(str, trace_shas))}, but {args.model}@"
                 f"{args.revision} is {sha}. The teacher must be the model that wrote the traces.")

    records = load_trace_records(args.traces)
    benchmarks = sorted({r["benchmark"] for r in records})
    problems = {p.id: p for b in benchmarks for p in load_problems(b)}
    examples, dropped = select_traces(records, problems, args.max_reasoning_tokens)
    print(f"[data] {len(examples)} traces kept from {len(records)} records; dropped {dropped}", flush=True)
    if args.limit is not None:
        examples = examples[: args.limit]

    tokenizer = AutoTokenizer.from_pretrained(args.model, revision=sha)
    for example in examples:
        example.keyword_ids = keyword_token_ids(example.reasoning, tokenizer)

    device = resolve_device(args.device)
    model = AutoModelForCausalLM.from_pretrained(args.model, revision=sha, dtype=default_dtype(device)).to(device).eval()
    meta = build_meta(args.model, sha, model.config.hidden_size, args.max_states, args.max_reasoning_tokens, args.traces)
    meta.update({"benchmarks": benchmarks, "kept": len(examples), "dropped": dropped, "limit": args.limit})

    os.makedirs(args.out_dir, exist_ok=True)
    started_at = provenance.now()
    with open(os.path.join(args.out_dir, f"manifest-{started_at.replace(':', '')}.json"), "w", encoding="utf-8") as f:
        json.dump({
            "started_at": started_at,
            "command": sys.argv,
            "device": str(device),
            "git": provenance.git_state(),
            "packages": provenance.package_versions(),
            "host": provenance.host(),
        }, f, indent=2)

    write_teacher_store(args.out_dir, examples, teacher_state_fn(model, tokenizer, args.max_states), meta, args.batch_size)
    print(f"[data] wrote {args.out_dir}", flush=True)


if __name__ == "__main__":
    main()
